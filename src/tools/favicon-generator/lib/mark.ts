const BOX = ["11111", "10001", "10001", "10001", "10001", "10001", "11111"];

export function glyphRows(char: string) {
  return GLYPHS[char] ?? BOX;
}

export function drawMark(text: string, background: Rgb, color: Rgb, size = 512) {
  const chars = [...text.toUpperCase()].slice(0, 3);
  const drawn = chars.length > 0 ? chars : ["?"];
  const glyphW = 5;
  const glyphH = 7;
  const gap = 1;
  const columns = drawn.length * glyphW + (drawn.length - 1) * gap;
  const scale = Math.max(1, Math.floor((size * 0.72) / Math.max(columns, glyphH)));
  const blockW = columns * scale;
  const blockH = glyphH * scale;
  const originX = Math.floor((size - blockW) / 2);
  const originY = Math.floor((size - blockH) / 2);
  const pixels = new Uint8Array(size * size * 4);
  for (let index = 0; index < pixels.length; index += 4) {
    pixels[index] = background.r;
    pixels[index + 1] = background.g;
    pixels[index + 2] = background.b;
    pixels[index + 3] = 255;
  }
  drawn.forEach((char, charIndex) => {
    const rows = glyphRows(char);
    const offset = charIndex * (glyphW + gap);
    rows.forEach((row, rowIndex) => {
      for (let column = 0; column < glyphW; column += 1) {
        if (row[column] !== "1") continue;
        for (let py = 0; py < scale; py += 1) {
          for (let px = 0; px < scale; px += 1) {
            const x = originX + (offset + column) * scale + px;
            const y = originY + rowIndex * scale + py;
            if (x < 0 || y < 0 || x >= size || y >= size) continue;
            const index = (y * size + x) * 4;
            pixels[index] = color.r;
            pixels[index + 1] = color.g;
            pixels[index + 2] = color.b;
          }
        }
      }
    });
  });
  return pixels;
}

export function inkCount(pixels: Uint8Array, color: Rgb) {
  let count = 0;
  for (let index = 0; index < pixels.length; index += 4) {
    if (pixels[index] === color.r && pixels[index + 1] === color.g && pixels[index + 2] === color.b) count += 1;
  }
  return count;
}
