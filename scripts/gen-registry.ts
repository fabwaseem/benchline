import { access, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { categories, toolOrder } from "../src/registry/categories";
import type { SearchRecord, ToolMeta } from "../src/registry/schema";
import { assertRegistry } from "../src/registry/validate";

async function main() {
const root = process.cwd();
const toolsDir = path.join(root, "src/tools");
const entries = await readdir(toolsDir, { withFileTypes: true });
const slugs = entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();

const metas: ToolMeta[] = [];
for (const slug of slugs) {
  const file = path.join(toolsDir, slug, "meta.ts");
  const loaded = (await import(pathToFileURL(file).href)) as { meta?: ToolMeta };
  if (!loaded.meta) throw new Error(`${slug}/meta.ts must export meta`);
  if (loaded.meta.slug !== slug) throw new Error(`${slug}/meta.ts slug does not match its folder`);
  metas.push(loaded.meta);
}

const tools = assertRegistry(metas, [...categories], toolOrder);
const records: SearchRecord[] = tools.map((tool) => ({
  slug: tool.slug,
  name: tool.name,
  tagline: tool.tagline,
  description: tool.description,
  category: tool.category,
  tags: tool.tags,
  keywords: tool.keywords,
  status: tool.status,
  icon: tool.icon,
  runsLocally: tool.runsLocally,
}));

const imports = tools
  .map((tool) => `import { meta as ${ident(tool.slug)} } from "@/tools/${tool.slug}/meta";`)
  .join("\n");
const idents = tools.map((tool) => ident(tool.slug)).join(", ");

const index = `// Generated by scripts/gen-registry.ts. Do not edit.
${imports}
import { categories, toolOrder } from "@/registry/categories";
import type { SearchRecord } from "@/registry/schema";
import { assertRegistry } from "@/registry/validate";

const tools = assertRegistry([${idents}], [...categories], toolOrder);

export { categories, tools };

export function getTool(slug: string) {
  return tools.find((tool) => tool.slug === slug);
}

export function getCategory(slug: string) {
  return categories.find((category) => category.slug === slug);
}

export function toolsInCategory(slug: string) {
  return tools.filter((tool) => tool.category === slug);
}

export function allTags() {
  const counts = new Map<string, number>();
  for (const tool of tools) {
    for (const tag of tool.tags) counts.set(tag, (counts.get(tag) ?? 0) + 1);
  }
  return [...counts.entries()]
    .map(([slug, count]) => ({ slug, count }))
    .sort((a, b) => a.slug.localeCompare(b.slug));
}

export function toolsWithTag(tag: string) {
  return tools.filter((tool) => tool.tags.includes(tag));
}

export function relatedTools(slug: string, limit = 4) {
  const tool = getTool(slug);
  if (!tool) return [];
  const bySlug = new Map(tools.map((item) => [item.slug, item]));
  return tool.related.flatMap((related) => {
    const match = bySlug.get(related);
    return match ? [match] : [];
  }).slice(0, limit);
}

export function searchRecords(): SearchRecord[] {
  return tools.map((tool) => ({
    slug: tool.slug,
    name: tool.name,
    tagline: tool.tagline,
    description: tool.description,
    category: tool.category,
    tags: [...tool.tags],
    keywords: [...tool.keywords],
    status: tool.status,
    icon: tool.icon,
    runsLocally: tool.runsLocally,
  }));
}
`;

const loaderLines = tools
  .map((tool) => `  "${tool.slug}": () => import("@/tools/${tool.slug}/tool"),`)
  .join("\n");
const loaders = `// Generated by scripts/gen-registry.ts. Do not edit.
import type { ComponentType } from "react";

export const toolLoaders: Record<string, () => Promise<{ default: ComponentType }>> = {
${loaderLines}
};
`;

const hostLines = tools
  .map((tool) => `  "${tool.slug}": dynamic(() => import("@/tools/${tool.slug}/tool")),`)
  .join("\n");
const host = `// Generated by scripts/gen-registry.ts. Do not edit.
"use client";

import dynamic from "next/dynamic";
import type { ComponentType } from "react";

const views: Record<string, ComponentType> = {
${hostLines}
};

export function ToolHost({ slug }: { slug: string }) {
  const View = views[slug];
  if (!View) return null;
  return <View />;
}
`;

const mcpImports: string[] = [];
const mcpIdents: string[] = [];
const mcpIndexEntries: string[] = [];
for (const tool of tools) {
  const mcpFile = path.join(toolsDir, tool.slug, "mcp.ts");
  try {
    await access(mcpFile);
  } catch {
    throw new Error(`${tool.slug} is missing mcp.ts`);
  }
  const loaded = (await import(pathToFileURL(mcpFile).href)) as {
    tool?: { slug: string; name: string; title: string; description: string; openWorld: boolean };
  };
  if (!loaded.tool) throw new Error(`${tool.slug}/mcp.ts must export tool`);
  if (loaded.tool.slug !== tool.slug) throw new Error(`${tool.slug}/mcp.ts slug does not match its folder`);
  const name = ident(tool.slug);
  mcpImports.push(`import { tool as ${name} } from "@/tools/${tool.slug}/mcp";`);
  mcpIdents.push(name);
  mcpIndexEntries.push(
    `  ${JSON.stringify({
      slug: loaded.tool.slug,
      name: loaded.tool.name,
      title: loaded.tool.title,
      description: loaded.tool.description,
      openWorld: loaded.tool.openWorld,
    })},`,
  );
}

const mcpRegistry = `// Generated by scripts/gen-registry.ts. Do not edit.
${mcpImports.join("\n")}
import type { BenchTool } from "@/lib/mcp/types";

export const mcpTools: BenchTool[] = [${mcpIdents.join(", ")}];

export function mcpToolBySlug(slug: string) {
  return mcpTools.find((tool) => tool.slug === slug);
}

export function mcpToolByName(name: string) {
  return mcpTools.find((tool) => tool.name === name);
}
`;

const mcpIndex = `// Generated by scripts/gen-registry.ts. Do not edit.
export type McpIndexEntry = {
  slug: string;
  name: string;
  title: string;
  description: string;
  openWorld: boolean;
};

export const mcpIndex: McpIndexEntry[] = [
${mcpIndexEntries.join("\n")}
];

export function mcpFor(slug: string) {
  return mcpIndex.find((tool) => tool.slug === slug);
}
`;

await writeFile(path.join(root, "src/registry/index.ts"), index);
await writeFile(path.join(root, "src/registry/loaders.ts"), loaders);
await writeFile(path.join(root, "src/components/site/tool-host.tsx"), host);
await writeFile(path.join(root, "src/registry/search-index.json"), `${JSON.stringify(records, null, 2)}\n`);
await writeFile(path.join(root, "src/registry/mcp-registry.ts"), mcpRegistry);
await writeFile(path.join(root, "src/registry/mcp-index.ts"), mcpIndex);

console.log(`registry: ${tools.length} tools`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});

function ident(slug: string) {
  const camel = slug.replace(/-([a-z0-9])/g, (_, char: string) => char.toUpperCase());
  return /^[0-9]/.test(camel) ? `tool${camel}` : camel;
}
