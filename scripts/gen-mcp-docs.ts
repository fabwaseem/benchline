import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { z } from "zod";
import { SITE_URL } from "../src/lib/site";
import { mcpTools } from "../src/registry/mcp-registry";

type JsonSchema = {
  type?: string | string[];
  description?: string;
  default?: unknown;
  enum?: unknown[];
  const?: unknown;
  items?: JsonSchema;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  format?: string;
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number;
  exclusiveMaximum?: number;
  minLength?: number;
  maxLength?: number;
  minItems?: number;
  maxItems?: number;
};

const docPath = resolve(process.cwd(), "docs/MCP.md");

function asSchema(schema: z.ZodType) {
  const json = z.toJSONSchema(schema, { io: "input" }) as JsonSchema & { $schema?: string };
  delete json.$schema;
  return json;
}

function literal(value: unknown) {
  if (typeof value === "string") return value.length === 0 ? '`""`' : `\`${value}\``;
  if (typeof value === "number" || typeof value === "boolean") return `\`${String(value)}\``;
  return `\`${JSON.stringify(value)}\``;
}

function typeOf(schema: JsonSchema): string {
  if (schema.enum && schema.enum.length > 0) return schema.enum.map((value) => literal(value)).join(" \\| ");
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.anyOf && schema.anyOf.length > 0) return schema.anyOf.map((item) => typeOf(item)).join(" or ");
  if (schema.oneOf && schema.oneOf.length > 0) return schema.oneOf.map((item) => typeOf(item)).join(" or ");
  const kind = Array.isArray(schema.type) ? schema.type.join(" \\| ") : schema.type;
  if (kind === "array") return schema.items ? `array of ${typeOf(schema.items)}` : "array";
  if (kind === "object") return "object";
  return kind ?? "value";
}

function constraints(schema: JsonSchema) {
  const notes: string[] = [];
  if (schema.format) notes.push(`format \`${schema.format}\``);
  if (schema.minLength !== undefined) notes.push(`min length ${schema.minLength}`);
  if (schema.maxLength !== undefined) notes.push(`max length ${schema.maxLength}`);
  if (schema.minimum !== undefined) notes.push(`minimum ${schema.minimum}`);
  if (schema.maximum !== undefined) notes.push(`maximum ${schema.maximum}`);
  if (schema.exclusiveMinimum !== undefined) notes.push(`exclusive minimum ${schema.exclusiveMinimum}`);
  if (schema.exclusiveMaximum !== undefined) notes.push(`exclusive maximum ${schema.exclusiveMaximum}`);
  if (schema.minItems !== undefined) notes.push(`min items ${schema.minItems}`);
  if (schema.maxItems !== undefined) notes.push(`max items ${schema.maxItems}`);
  return notes;
}

function fields(schema: JsonSchema, indent: string): string[] {
  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const lines: string[] = [];
  for (const [name, property] of Object.entries(properties)) {
    const bits = [typeOf(property)];
    bits.push(required.has(name) ? "required" : "optional");
    if (property.default !== undefined) bits.push(`default ${literal(property.default)}`);
    bits.push(...constraints(property));
    const description = property.description ? ` — ${property.description}` : "";
    lines.push(`${indent}- \`${name}\` (${bits.join(", ")})${description}`);
    if (property.properties) lines.push(...fields(property, `${indent}  `));
    if (property.items?.properties) lines.push(...fields(property.items, `${indent}  `));
  }
  return lines;
}

function block(title: string, schema: JsonSchema) {
  const lines = fields(schema, "");
  if (lines.length === 0) return [`### ${title}`, "", "No fields.", ""];
  return [`### ${title}`, "", ...lines, ""];
}

const parts = [
  "# MCP reference",
  "",
  "Generated by `pnpm gen:mcp-docs` from the registry. Do not edit the tool entries by hand.",
  "",
  `Endpoint: \`${SITE_URL}/mcp\`. Stateless Streamable HTTP. JSON responses, no session, no API key. \`POST\` only. \`GET\` and \`DELETE\` return 405.`,
  "",
  `Each tool below is also \`POST ${SITE_URL}/api/v1/tools/<slug>\` with the same JSON input. The operation id in [${SITE_URL}/openapi.json](${SITE_URL}/openapi.json) is the MCP name.`,
  "",
  "Sixty calls a minute per address on `/mcp` and on `/api/v1/tools/<slug>`. A 429 includes `retry-after`. The limit reads the first `x-forwarded-for` hop, then `x-real-ip`.",
  "",
  "A request with an `Origin` header must match the request host, `localhost`, `127.0.0.1`, or the site origin. A request with no `Origin` is allowed.",
  "",
  "File fields take either `url` or `data`, not both. `data` is base64 or a data URI, decoded to at most 10 MB. `url` must be public `http` or `https` on port 80 or 443, with no userinfo. Local, private, link-local, and CGNAT addresses are refused, including after DNS lookup and after up to four redirects. The fetch times out after 15 seconds.",
  "",
  "The handler validates with the input schema, runs the tool, and validates the output. A thrown error comes back as `isError: true` and a text message. It is not a successful result.",
  "",
  "Every registered tool is listed below.",
  "",
];

for (const tool of mcpTools) {
  parts.push(
    `## \`${tool.name}\``,
    "",
    `**${tool.title}**`,
    "",
    tool.description,
    "",
    `- Page: ${SITE_URL}/t/${tool.slug}`,
    `- HTTP: \`POST ${SITE_URL}/api/v1/tools/${tool.slug}\``,
    `- Fetches the network: ${tool.openWorld ? "yes" : "no"}`,
    "",
    ...block("Input", asSchema(tool.inputSchema)),
  );
}

writeFileSync(docPath, `${parts.join("\n").trim()}\n`);
console.log(`mcp docs: ${mcpTools.length} tools`);
