const results = [];
const tools = listed.tools;
for (const tool of tools) {
  const args = samples[tool.name];
  const row = {
    name: tool.name,
    title: tool.title ?? tool.annotations?.title ?? "",
    description: tool.description ?? "",
    annotations: tool.annotations ?? {},
    hasOutputSchema: Boolean(tool.outputSchema),
    required: tool.inputSchema?.required ?? [],
    sampled: Boolean(args),
  };
  if (!args) {
    row.status = "skipped";
    row.note = "no sample input in this script";
    results.push(row);
    continue;
  }
  const started = performance.now();
  try {
    const result = await client.callTool({ name: tool.name, arguments: args });
    row.ms = Math.round(performance.now() - started);
    row.bytes = JSON.stringify(result).length;
    row.status = result.isError ? "error" : "ok";
    row.text = textOf(result).slice(0, 400);
    row.structured = result.structuredContent ? preview(result.structuredContent) : null;
    row.contentTypes = (result.content ?? []).map((b) => b.type);
    if (!result.isError && tool.outputSchema && !result.structuredContent) row.note = "outputSchema declared but no structuredContent";
  } catch (error) {
    row.ms = Math.round(performance.now() - started);
    row.status = "exception";
    row.text = String(error?.message ?? error).slice(0, 400);
  }
  console.log(`${row.status.padEnd(9)} ${String(row.ms).padStart(6)}ms  ${tool.name}${row.status !== "ok" ? `  → ${row.text?.slice(0, 120)}` : ""}`);
  results.push(row);
  await sleep(1100); // stay under the 60 calls/min limit
}

const extraResults = [];
for (const check of extras) {
  const started = performance.now();
  let status;
  let text;
  try {
    const result = await client.callTool({ name: check.name, arguments: check.args });
    status = result.isError ? "error" : "ok";
    text = textOf(result);
  } catch (error) {
    status = "error";
    text = String(error?.message ?? error);
  }
  const ms = Math.round(performance.now() - started);
  extraResults.push({ ...check, args: undefined, status, pass: status === check.expect, ms, text: text.slice(0, 400) });
  console.log(`${status === check.expect ? "PASS" : "FAIL"} ${check.label} → ${text.slice(0, 120)}`);
  await sleep(1100);
}

await client.close();

// Raw HTTP checks: what a client sees before speaking MCP.
async function http(label, url, init) {
  try {
    const response = await fetch(url, init);
    const body = await response.text();
    return { label, status: response.status, contentType: response.headers.get("content-type"), allow: response.headers.get("allow"), body: body.slice(0, 300) };
  } catch (error) {
    return { label, error: String(error) };
  }
}
