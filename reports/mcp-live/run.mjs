function textOf(result) {
  for (const block of result?.content ?? []) if (block?.type === "text") return block.text;
  return "";
}

function preview(value, max = 220) {
  const replacer = (_key, v) => (typeof v === "string" && v.length > 120 ? `${v.slice(0, 60)}…(${v.length} chars)` : v);
  const text = JSON.stringify(value, replacer) ?? "";
  return text.length > max ? `${text.slice(0, max)}…` : text;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function connect() {
  const client = new Client({ name: "benchline-live-check", version: "1.0.0" });
  const transport = new StreamableHTTPClientTransport(new URL(endpoint));
  const started = performance.now();
  await client.connect(transport);
  return { client, connectMs: Math.round(performance.now() - started) };
}

